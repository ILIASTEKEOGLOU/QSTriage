"""PDR compatibility corpus: issued PDRs keep verifying with their own hashes.

The corpus in ``tests/fixtures/pdr_compat`` holds PDRs generated by released
versions and by the development line, in plain and Unicode form. Every file is
stored as ASCII. A Unicode original is stored with ASCII escapes; the tests
rebuild its exact UTF-8 bytes in a temporary file, check the recorded SHA-256,
and verify the rebuilt file. The escaped file itself is a second, valid
encoding of the same document and must verify with the same hashes.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any

import pytest
from typer.testing import CliRunner

from qstriage.cli import app
from qstriage.pdr_diff import diff_pdr_files
from qstriage.pdr_verify import verify_pdr_file


CORPUS = Path(__file__).resolve().parent / "fixtures" / "pdr_compat"
MANIFEST: dict[str, Any] = json.loads((CORPUS / "manifest.json").read_text(encoding="ascii"))
ENTRIES = MANIFEST["files"]
PDR_ENTRIES = [entry for entry in ENTRIES if entry["pdr_version"] is not None]
UNICODE_PDR_ENTRIES = [entry for entry in PDR_ENTRIES if entry["rebuild"] is not None]


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _rebuild(entry: dict[str, Any]) -> bytes:
    stored = (CORPUS / entry["stored"]).read_bytes()
    if entry["rebuild"] is None:
        return stored
    if entry["rebuild"] == "pdr_json":
        # QSTriage writes PDRs as two-space indented JSON with literal
        # Unicode characters and a final newline.
        document = json.loads(stored.decode("ascii"))
        return (json.dumps(document, indent=2, ensure_ascii=False) + "\n").encode("utf-8")
    if entry["rebuild"] == "json_string":
        return json.loads(stored.decode("ascii")).encode("utf-8")
    raise AssertionError(f"unknown rebuild method {entry['rebuild']!r}")


def _materialize(entry: dict[str, Any], directory: Path) -> Path:
    name = entry["stored"].replace(".escaped.json", ".json")
    path = directory / name
    path.write_bytes(_rebuild(entry))
    return path


def _ids(entries: list[dict[str, Any]]) -> list[str]:
    return [entry["stored"] for entry in entries]


def test_manifest_lists_every_stored_file() -> None:
    stored = {entry["stored"] for entry in ENTRIES} | {"manifest.json"}
    assert stored == {path.name for path in CORPUS.iterdir()}


@pytest.mark.parametrize("entry", ENTRIES, ids=_ids(ENTRIES))
def test_stored_file_is_ascii_and_unchanged(entry: dict[str, Any]) -> None:
    data = (CORPUS / entry["stored"]).read_bytes()

    assert data.isascii()
    assert b"\r" not in data
    assert _sha256(data) == entry["stored_sha256"]


@pytest.mark.parametrize("entry", ENTRIES, ids=_ids(ENTRIES))
def test_rebuilt_file_matches_its_original_sha256(entry: dict[str, Any]) -> None:
    assert _sha256(_rebuild(entry)) == entry["original_sha256"]


@pytest.mark.parametrize("entry", PDR_ENTRIES, ids=_ids(PDR_ENTRIES))
def test_original_bytes_verify_with_their_issued_hashes(
    entry: dict[str, Any], tmp_path: Path
) -> None:
    result = verify_pdr_file(_materialize(entry, tmp_path))

    assert result.passed
    assert result.pdr_version == entry["pdr_version"]
    assert len(result.checks) == entry["checks"]


@pytest.mark.parametrize("entry", UNICODE_PDR_ENTRIES, ids=_ids(UNICODE_PDR_ENTRIES))
def test_escaped_encoding_verifies_with_the_same_hashes(entry: dict[str, Any]) -> None:
    result = verify_pdr_file(CORPUS / entry["stored"])

    assert result.passed
    assert result.pdr_version == entry["pdr_version"]
    assert len(result.checks) == entry["checks"]


@pytest.mark.parametrize("entry", UNICODE_PDR_ENTRIES, ids=_ids(UNICODE_PDR_ENTRIES))
def test_unicode_pdr_records_the_hash_of_its_source_inventory(entry: dict[str, Any]) -> None:
    (inventory,) = [item for item in ENTRIES if item["rebuild"] == "json_string"]
    document = json.loads(_rebuild(entry))

    assert document["input_snapshot"]["source_hash"] == "sha256:" + inventory["original_sha256"]


def test_unicode_name_survives_in_original_bytes() -> None:
    (entry,) = [item for item in ENTRIES if item["stored"] == "v1.2.1-unicode.escaped.json"]
    name = json.loads(_rebuild(entry))["records"][0]["observed_state"]["asset_name"]

    # Greek text, a composed and a decomposed accent, and an emoji.
    assert name == (
        "\u0391\u03c1\u03c7\u03b5\u03af\u03bf Caf\u00e9 / Cafe\u0301 \U0001f510"
    )


def test_repository_fixture_is_unchanged_and_verifies() -> None:
    fixture = MANIFEST["repository_fixture"]
    path = (CORPUS / fixture["path"]).resolve()
    result = verify_pdr_file(path)

    assert _sha256(path.read_bytes()) == fixture["sha256"]
    assert result.passed
    assert result.pdr_version == fixture["pdr_version"]
    assert len(result.checks) == fixture["checks"]


@pytest.mark.parametrize("variant", ["plain", "unicode"])
def test_cross_version_diff_keeps_format_and_decision_changes_apart(
    variant: str, tmp_path: Path
) -> None:
    def path_for(version: str) -> Path:
        stored = f"v{version}-{variant}.json"
        if variant == "unicode":
            stored = f"v{version}-unicode.escaped.json"
        (entry,) = [item for item in ENTRIES if item["stored"] == stored]
        return _materialize(entry, tmp_path)

    diff = diff_pdr_files(path_for("1.2.1"), path_for("1.4.1"))

    assert "registry_context" in diff.format_differences
    assert not diff.added and not diff.removed
    if variant == "unicode":
        (change,) = diff.changed
        changes = {item.field: (item.before, item.after) for item in change.changes}
        assert changes["decision.confidence_score"] == (0.8, 0.65)
        assert set(changes) == {"decision.confidence_score", "decision.reason_codes"}
    else:
        assert not diff.changed


def test_cli_verifies_rebuilt_unicode_pdr(tmp_path: Path) -> None:
    (entry,) = [item for item in ENTRIES if item["stored"] == "v1.4.1-unicode.escaped.json"]
    path = _materialize(entry, tmp_path)

    result = CliRunner().invoke(app, ["pdr", "verify", str(path)])

    assert result.exit_code == 0
    assert "PASS (pdr_version 0.3, 8 of 8 checks passed)" in result.output
